/** 시도 풀네임 → 약칭. 매핑에 없으면 마지막 접미사(특별시/광역시/도/직할시/통합특별시 등) 제거 fallback. */
export function shortSido(name: string | null | undefined): string {
  if (!name) return "";
  return (
    SIDO_SHORT[name] ??
    name.replace(
      /(특별시|광역시|특별자치시|특별자치도|직할시|통합특별시|도)$/u,
      "",
    )
  );
}
