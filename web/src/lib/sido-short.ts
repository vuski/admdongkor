  // 통합시. 정부 공식 약칭은 '광주' — 접미사만 떼면 '전남광주' 가 되므로
  // 반드시 명시해야 한다 (fallback 에 맡기면 안 됨).
  // 광주광역시·광주직할시와 약칭이 겹치지만, 셋은 계승 관계상 같은 지역이고
  // 라벨은 한 시점만 그리므로 한 화면에 동시에 등장하지 않는다.
  전남광주통합특별시: "광주",
